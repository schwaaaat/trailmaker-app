/* ================================================================ worker */

/** Progress event delivered to the main thread. */
export interface JobProgress {
  /** Job this refers to. */
  readonly jobId: JobId;
  /** 0..1. */
  readonly fraction: number;
  /** Short stage label, e.g. "Thinning". */
  readonly stage: string;
}

/** Per-call job control. onProgress crosses the worker boundary as a Comlink proxy. */
export interface JobControl {
  /** Caller-chosen id; pass to WorkerApi.cancel. */
  readonly jobId: JobId;
  /** Optional progress callback. */
  readonly onProgress?: (p: JobProgress) => void;
}

/**
 * Everything the worker exposes (Comlink). Heavy jobs are cancellable: cancel(jobId)
 * makes the pending promise reject with an Error named JOB_CANCELLED within 100 ms.
 * Rasters are transferred once with loadImage and stay in the worker.
 */
export interface WorkerApi {
  /** Take ownership of a raster (transfer its buffer); returns a handle for later jobs. */
  loadImage(image: RasterImage): Promise<ImageId>;
  /** Free a raster. */
  releaseImage(id: ImageId): Promise<void>;
  /** Dominant ink color near a click (prototype pickInk). radiusPx is clamped 1..14. */
  pickInk(id: ImageId, at: Px, radiusPx: number): Promise<Rgb>;
  /** Nearest pixel matching ink within radius, or null (prototype snap). */
  snapToInk(id: ImageId, at: Px, ink: Rgb, tolerance: number, radiusPx: number): Promise<Px | null>;
  /** One smart-follow hop. */
  smartTrace(req: SmartTraceRequest, ctl: JobControl): Promise<SmartTraceResult>;
  /** Find colors drawn as thin lines. */
  scanColors(id: ImageId, ctl: JobControl): Promise<ColorScanResult>;
  /** Auto-trace candidate lines for the given colors. */
  autoTrace(req: AutoTraceRequest, ctl: JobControl): Promise<readonly AutoTraceCandidate[]>;
  /** Build a KMZ archive (doc.kml + overlay image). */
  buildKmz(req: KmzRequest, ctl: JobControl): Promise<Uint8Array>;
  /** Cancel a running or queued job; no-op if unknown or finished. */
  cancel(jobId: JobId): Promise<void>;
}
