  /** Project name (export document name). */
  readonly name: string;
  /** The map this project traces. */
  readonly image: MapImage;
  /** Ground control points in creation order (the UI numbers them 1..n). */
  readonly anchors: readonly Anchor[];
  /** Requested fit method. */
