/* ================================================================ history */

/**
 * An undoable edit. Every change to Project goes through one. apply/revert are pure:
 * revert(apply(p)) must deep-equal p, which is what makes undo/redo exact.
 */
export interface HistoryCommand {
  /** Short user-visible label, e.g. "Move vertex", shown as "Undo Move vertex". */
  readonly label: string;
  /** Returns the project with the edit applied. */
  apply(project: Project): Project;
  /** Returns the project with the edit undone. */
  revert(project: Project): Project;
  /** Consecutive commands with the same non-null key (e.g. typing a name) coalesce into one undo step. */
  readonly coalesceKey: string | null;
}

/** Max undo depth (prototype: 120). */
export const HISTORY_LIMIT = 120;

/* ================================================================ tracing */

/** Options shared by the color-following tools. */
export interface TraceOptions {
  /** Color distance tolerance, Euclidean RGB. */
  readonly tolerance: number;
}

/** One smart-follow hop: least-cost path from `from` to `to` preferring pixels near `ink`. */
export interface SmartTraceRequest extends TraceOptions {
  /** Raster to trace on (worker handle). */
  readonly imageId: ImageId;
  /** Start of the hop (the draft's last vertex; not re-snapped). */
  readonly from: Px;
  /** Where the user clicked; snapped to ink within snapRadiusPx first. */
  readonly to: Px;
  /** Ink color to follow. */
  readonly ink: Rgb;
  /** Snap radius in pixels (prototype: 8 screen px / zoom, clamped 2..30). */
  readonly snapRadiusPx: number;
}

/** Result of a smart-follow hop. */
export interface SmartTraceResult {
  /** Path from `from` to `snappedTo` inclusive, simplified (Douglas-Peucker 0.9 px); null if the hop was too large or unreachable. */
  readonly path: readonly Px[] | null;
  /** The click after snapping to ink (== request.to when nothing matched). */
  readonly snappedTo: Px;
  /** Wall time spent in the worker, ms. */
  readonly ms: number;
}

/** A color the scan found drawn as thin lines. */
export interface ScannedColor {
  /** Mean color of the cluster. */
  readonly rgb: Rgb;
  /** Human color name from nameColor (e.g. "Blue"). */
  readonly name: string;
  /** Fraction of sampled pixels in this cluster. */
  readonly share: number;
  /** Edge pixels / cluster pixels; high means thin strokes. */
  readonly thinness: number;
  /** HSL saturation 0..1. */
  readonly saturation: number;
  /** HSL lightness 0..1. */
  readonly lightness: number;
  /** Ranking score (prototype: share * thinness * (0.35 + saturation)). */
  readonly score: number;
  /** True when it looks like a trail color and should be pre-ticked. */
  readonly likely: boolean;
}

/** Output of a color scan, best first, at most 10 colors. */
export interface ColorScanResult {
  /** Candidate trail colors. */
  readonly colors: readonly ScannedColor[];
}

/** Auto-trace one or more colors into candidate lines. */
export interface AutoTraceRequest extends TraceOptions {
  /** Raster to trace (worker handle). */
  readonly imageId: ImageId;
  /** Colors to trace, each producing its own candidates. */
  readonly colors: readonly { readonly chipId: ChipId; readonly rgb: Rgb }[];
  /** Gap bridging distance in pixels (0 = off). */
  readonly gapPx: number;
  /** Candidates shorter than this (pixels) are dropped. */
  readonly minLengthPx: number;
  /** M2: join candidates of different colors that continue each other (a trail that changes color). Default false. */
  readonly mergeAcrossColors?: boolean;
}

/** A line found by auto-trace, awaiting user review. */
export interface AutoTraceCandidate {
  /** Id unique within one auto-trace result. */
  readonly id: CandidateId;
  /** Chip whose color produced it. */
  readonly chipId: ChipId;
  /** Polyline, simplified. */
  readonly pts: readonly Px[];
  /** Length in pixels. */
  readonly lengthPx: number;
  /** Ink color traced. */
  readonly ink: Rgb;
  /** 0..1 confidence that this is a real trail (M2); null until implemented. */
  readonly confidence: number | null;
  /** M2: other chips whose lines were merged into this candidate (mergeAcrossColors); absent or empty otherwise. */
  readonly alsoChips?: readonly ChipId[];
}

/**
 * Hooks passed into long-running core functions. Core calls progress() at stage
 * boundaries and at least every ~50 ms of work, and calls throwIfCancelled() at least
 * that often; it throws a JobCancelledError to abort.
 */
export interface JobHooks {
  /** Report progress: fraction 0..1 of the whole job, and a short stage label. */
  progress(fraction: number, stage: string): void;
  /** Throws JobCancelledError if the job was cancelled. */
  throwIfCancelled(): void;
}

/** Name of the error thrown when a job is cancelled (Error.name === JOB_CANCELLED). */
export const JOB_CANCELLED = 'JobCancelled';

