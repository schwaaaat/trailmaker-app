// THE CONTRACT. Only the Architect edits this file, as its own "CONTRACT: ..." commit on
// integration. Pure TypeScript: no DOM types, no package imports, no runtime behavior
// beyond a few constant tables. Every lane compiles against it.
//
// Conventions
// - Pixel coordinates (Px) are in the *working raster* of the map (MapImage.width/height),
//   origin top-left, x right, y down. Features and anchors store pixels; lat/lon is derived
//   through a GeoFit at display/export time.
// - LatLon is [lat, lon] in WGS84 degrees (the prototype's order). Writers that need
//   lon,lat (KML, GeoJSON) swap on output.
// - Distances are meters unless a name says otherwise (…Px for pixels).
// - All contract data is plain, structured-clone-safe JSON-like data (no class instances,
//   no functions) except where a member is explicitly a callback or command object.

/* ================================================================ primitives */

/** A point in working-raster pixel coordinates: [x, y]. */
export type Px = readonly [x: number, y: number];

/** A WGS84 position in degrees: [lat, lon]. */
export type LatLon = readonly [lat: number, lon: number];

/** An 8-bit RGB color, each channel 0..255 (may be fractional mid-computation). */
export type Rgb = readonly [r: number, g: number, b: number];

/** A CSS hex color, "#rrggbb" lower- or upper-case. */
export type HexColor = string;

/** Opaque string ids. Generated by the state layer (src/state), unique within a project. */
export type AnchorId = string;
/** Id of a Feature (trail, POI or area). */
export type FeatureId = string;
/** Id of an auto-trace color chip. */
export type ChipId = string;
/** Id of an auto-trace candidate line (not persisted). */
export type CandidateId = string;
/** Handle for a raster held inside the worker (see WorkerApi.loadImage). */
export type ImageId = string;
/** Caller-chosen id for a worker job, used by WorkerApi.cancel. */
export type JobId = string;

/** Length units shown in the UI and written into export descriptions. */
export type Units = 'mi' | 'km';

/** An RGBA raster, row-major, 4 bytes per pixel. Structurally compatible with DOM ImageData. */
export interface RasterImage {
  /** Width in pixels. */
  readonly width: number;
  /** Height in pixels. */
  readonly height: number;
  /** RGBA bytes, length = width * height * 4. */
  readonly data: Uint8ClampedArray;
}

/* ================================================================ map image */

/** Where the working raster came from. */
export type MapSource =
  /** A bitmap file (PNG/JPG/WebP/…); mimeType is the original file's type. */
  | { readonly kind: 'image'; readonly mimeType: string }
  /** One page of a PDF rendered to a bitmap at renderScale (PDF points -> pixels). */
  | { readonly kind: 'pdf'; readonly page: number; readonly pageCount: number; readonly renderScale: number };

/** Metadata about the map image a project traces over. The pixels themselves live outside the project JSON. */
export interface MapImage {
  /** Display name, usually the file name without extension. */
  readonly fileName: string;
  /** Working raster width in pixels (the coordinate space of every Px). */
  readonly width: number;
  /** Working raster height in pixels. */
  readonly height: number;
  /** Width of the original image before the working-resolution cap (== width if not scaled). */
  readonly originalWidth: number;
  /** Height of the original image before the working-resolution cap. */
  readonly originalHeight: number;
  /** Origin of the raster. */
  readonly source: MapSource;
  /** Lower-case hex SHA-256 of the original file bytes; lets autosave/project files verify the image. */
  readonly sha256: string;
  /**
   * Imagery credit for maps captured from an imagery service (T-318/T-320), e.g.
   * "Imagery: USDA NAIP via USGS The National Map". Shown in the app and written into KML/KMZ.
   * Absent for maps opened from a file.
   */
  readonly attribution?: string;
  /** Year the imagery was acquired, when the provider reports it (NAIP, T-320). */
  readonly acquisitionYear?: number;
}

/** Longest side, in pixels, of the working raster. Larger images are downscaled for tracing; the original is kept for export. */
export const MAX_WORKING_SIDE = 7000;

/* ================================================================ anchors & fit */

/** How an anchor's real-world position was entered. */
export type AnchorSource = 'paste' | 'basemap';

/** A ground control point: a pixel on the map tied to a real-world position. */
export interface Anchor {
  /** Stable id. */
  readonly id: AnchorId;
  /** Location on the map image. */
  readonly px: Px;
  /** Real-world position, or null while the user has placed the pin but not entered coordinates. */
  readonly ll: LatLon | null;
  /** How ll was entered (M2 adds 'basemap'). */
  readonly source: AnchorSource;
}

/** Fit method requested by the user. 'auto' = affine with >= 4 anchors, else similarity (prototype rule). */
export type FitMethod = 'auto' | 'similarity' | 'affine' | 'tps';

/** Fit method actually used after fallbacks (e.g. TPS with < 4 anchors falls back to affine). */
export type ResolvedFitMethod = Exclude<FitMethod, 'auto'>;

/**
 * Local planar frame the fit is solved in (prototype Core.fit): pixels are normalized
 * u = (x - cx) / scale, v = (y - cy) / scale; geography is local east/north meters
 * E = (lon - lon0) * kx, N = (lat - lat0) * ky around the anchor centroid.
 */
export interface FitFrame {
  /** Latitude of the anchor centroid (degrees). */
  readonly lat0: number;
  /** Longitude of the anchor centroid (degrees). */
  readonly lon0: number;
  /** Meters per degree of longitude at lat0. */
  readonly kx: number;
  /** Meters per degree of latitude. */
  readonly ky: number;
  /** Pixel x of the normalization center (image width / 2). */
  readonly cx: number;
  /** Pixel y of the normalization center (image height / 2). */
  readonly cy: number;
  /** Pixel normalization scale (max(width, height)). */
  readonly scale: number;
}

/** Row-major 2x3 affine map from normalized (u, v) to (E, N): E = m[0]u + m[1]v + m[2], N = m[3]u + m[4]v + m[5]. */
export type Affine2x3 = readonly [number, number, number, number, number, number];

/** The solved transform. Serializable so it can cross the worker boundary and be cached. */
export type FitModel =
  /** Similarity (scale + rotation + translation, no mirroring), stored as its equivalent affine. */
  | { readonly kind: 'similarity'; readonly affine: Affine2x3 }
  /** Least-squares affine. */
  | { readonly kind: 'affine'; readonly affine: Affine2x3 }
  /**
   * Thin-plate spline with r^2 log r^2 kernel in normalized coordinates.
   * weightsE/weightsN have length controls.length + 3: kernel weights then [a0, au, av].
   */
  | {
      readonly kind: 'tps';
      readonly controls: readonly (readonly [u: number, v: number])[];
      readonly weightsE: readonly number[];
      readonly weightsN: readonly number[];
      /** Best-fit affine of the same anchors; used for inverse seeding and residual checks. */
      readonly affine: Affine2x3;
    };

/** A successful georeference: everything needed to map pixels to lat/lon and judge quality. */
export interface GeoFit {
  /** Discriminant. */
  readonly ok: true;
  /** Method the user asked for. */
  readonly requested: FitMethod;
  /** Method actually used. */
  readonly method: ResolvedFitMethod;
  /** Normalization frame. */
  readonly frame: FitFrame;
  /** Solved transform. */
  readonly model: FitModel;
  /** Number of anchors with coordinates that went into the fit. */
  readonly anchorCount: number;
  /**
   * Per-anchor residual in meters. For TPS these come from the companion affine
   * (a TPS interpolates exactly, so its own residuals are zero) — prototype behavior.
   */
  readonly residuals: Readonly<Record<AnchorId, number>>;
  /** Root-mean-square of residuals, meters. */
  readonly rms: number;
  /** True when there are more anchors than the model's degrees of freedom need, so residuals mean something. */
  readonly checked: boolean;
  /** Leave-one-out residuals in meters (each anchor predicted by a fit of the others). Null until computed (M2). */
  readonly looResiduals: Readonly<Record<AnchorId, number>> | null;
  /** Ground meters per working-raster pixel (geometric mean scale). */
  readonly metersPerPixel: number;
  /** True when the anchors describe a mirror image (e.g. lat/lon swapped on one anchor). */
  readonly mirrored: boolean;
  /** True when metersPerPixel is outside PLAUSIBLE_METERS_PER_PIXEL. */
  readonly implausibleScale: boolean;
}

/** Why a fit could not be produced. */
export interface FitFailure {
  /** Discriminant. */
  readonly ok: false;
  /** 'too-few': fewer than 2 anchors with coordinates. 'degenerate': anchors coincide or are collinear for the method. */
  readonly reason: 'too-few' | 'degenerate';
  /** Anchors with coordinates that were available. */
  readonly anchorCount: number;
  /** How many more anchors with coordinates are needed (0 when degenerate). */
  readonly need: number;
}

/** Result of fitting anchors. */
export type FitResult = GeoFit | FitFailure;

/** Plausible park-map scale range in meters per pixel (prototype: warn outside 0.005..200). */
export const PLAUSIBLE_METERS_PER_PIXEL = { min: 0.005, max: 200 } as const;

/** Residual above which an anchor is flagged as the odd one out: max(OUTLIER_MIN_M, rms * OUTLIER_RMS_FACTOR). */
export const OUTLIER_MIN_M = 25;
/** See OUTLIER_MIN_M. */
export const OUTLIER_RMS_FACTOR = 2.2;

/* ================================================================ features */

/** Point-of-interest categories; each maps to a GPX <sym> and a KML icon in src/core/export. */
export const POI_TYPES = [
  'Trailhead',
  'Parking',
  'Restroom',
  'Viewpoint',
  'Campsite',
  'Water',
  'Information',
  'Junction',
  'Waypoint',
] as const;

/** One of POI_TYPES. */
export type PoiType = (typeof POI_TYPES)[number];

/** Fields every feature has. */
export interface FeatureBase {
  /** Stable id. */
  readonly id: FeatureId;
  /** User-visible name. */
  readonly name: string;
  /** Display and export color. */
  readonly color: HexColor;
  /** Free-text notes, exported as description. */
  readonly notes: string;
}

/** A traced trail: an open polyline. */
export interface Trail extends FeatureBase {
  /** Discriminant. */
  readonly kind: 'trail';
  /** Vertices in order, length >= 2. */
  readonly pts: readonly Px[];
  /** Ink color the trail was traced along (for smart "continue"), or null if drawn by hand. */
  readonly ink: Rgb | null;
}

/** A point of interest. */
export interface Poi extends FeatureBase {
  /** Discriminant. */
  readonly kind: 'poi';
  /** Location. */
  readonly at: Px;
  /** Category. */
  readonly poiType: PoiType;
}

/** A closed area (polygon). pts is the open ring; the closing edge is implied. */
export interface Area extends FeatureBase {
  /** Discriminant. */
  readonly kind: 'area';
  /** Ring vertices without repeating the first, length >= 3. */
  readonly pts: readonly Px[];
}

/** Any traced feature. */
export type Feature = Trail | Poi | Area;

/** Feature discriminant values. */
export type FeatureKind = Feature['kind'];

/** Default colors (prototype): trail, area, POI. */
export const DEFAULT_COLORS = { trail: '#D9480F', area: '#3A7D44', poi: '#1F6FB2' } as const;

/* ================================================================ project */

/** A trail color the user wants auto-trace to follow. */
export interface ColorChip {
  /** Stable id. */
  readonly id: ChipId;
  /** Ink color on the map. */
  readonly rgb: Rgb;
  /** Name used for candidate trails (legend name or color name). */
  readonly name: string;
  /** Whether auto-trace uses this chip. */
  readonly enabled: boolean;
  /** Share of map pixels in this color (from a scan), or null when picked by hand. */
  readonly share: number | null;
  /** True when name came from the user or a legend (candidate names then use "(part n)"). */
  readonly named: boolean;
}

/** Tracing settings persisted with the project. */
export interface TraceSettings {
  /** Smart follow on/off for the trail tool. */
  readonly smartFollow: boolean;
  /** Color distance tolerance (Euclidean RGB, 0..442), prototype default 60. */
  readonly tolerance: number;
  /** User-picked ink to follow, or null to pick from the first click (prototype "autoInk"). */
  readonly ink: Rgb | null;
}

/** Auto-trace settings persisted with the project. */
export interface AutoTraceSettings {
  /** Colors to trace. */
  readonly chips: readonly ColorChip[];
  /** Max gap in pixels to bridge between line ends (dashes, crossings); 0 = off. Default round(max(W,H)/80) clamped 6..120. */
  readonly gapPx: number;
  /** Minimum candidate length as a percentage of max(W, H). Default 4. */
  readonly minLengthPct: number;
}

/** Current project schema version. Bump with a migration in src/core/project. v2 (D-024): v1 plus an optional imported.gpx zip entry. */
